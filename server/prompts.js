export function buildVisionUserPrompt({ cropName, note }) {
  const parts = ['આ પાકના ફોટાનું વિશ્લેષણ કરો અને ઉપર જણાવેલ JSON ફોર્મેટમાં જ ગુજરાતીમાં જવાબ આપો.'];
  if (cropName) parts.push(`ખેડૂતે પાકનું નામ જણાવ્યું છે: ${cropName}.`);
  if (note) parts.push(`ખેડૂતની નોંધ: ${note}`);
  parts.push('યાદ રાખો: ફક્ત ફોટામાં દેખાતી વાત પરથી અંદાજ, અને શંકા હોય તો નિષ્ણાતની સલાહ જણાવો.');
  return parts.join('\n');
}

